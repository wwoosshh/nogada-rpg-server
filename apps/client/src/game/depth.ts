/**
 * 렌더 깊이. 값이 클수록 위에 그려진다.
 *
 * 타일맵의 핵심 규칙: **렌더링 층위와 충돌 여부는 별개다.**
 * `decor` 는 바닥 위에 그려지지만 통과할 수 있고(카펫, 꽃),
 * `overhead` 는 플레이어보다 위에 그려져 나뭇잎이나 지붕 끝 뒤로 걸어갈 수 있게 한다.
 * 충돌은 오직 `walls` 레이어만 담당한다.
 *
 * `overhead` 가 플레이어 위에 오는 것은 생성 순서가 아니라 이 숫자 때문이다 —
 * Phaser 는 씬에 추가된 순서가 아니라 depth 값으로 그리는 순서를 정렬한다.
 *
 * WorldScene 과 NodeMarker 가 함께 참조하는 단일 출처다. 씬이 노드 마커의
 * 깊이를 정의하거나 그 반대가 되지 않도록, 어느 쪽에도 속하지 않는 이
 * 작은 모듈에 둔다.
 *
 * `dayNight` 아래의 것은 밤에 어두워지고 위의 것은 어두워지지 않는다.
 * 피드백 글자를 위에 두는 것은 연출보다 가독성이 우선이기 때문이다.
 */
