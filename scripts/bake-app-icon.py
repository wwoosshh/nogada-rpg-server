#!/usr/bin/env python3
"""홈 화면 아이콘을 32x32 픽셀 격자에서 구워 낸다.

    python scripts/bake-app-icon.py

**왜 그림 파일을 손으로 안 두고 스크립트를 두는가.** 이 아이콘은 자체 제작이라
저장소에 커밋되는데(라이선스 에셋 넷과 달리 — 루트 .gitignore 참고), 커밋된
PNG 는 무엇으로 만들었는지 자기 안에 안 적는다. 색을 한 칸 바꾸고 싶은 날
192 와 512 를 각각 손으로 찍으면 둘이 갈라지고, 갈라진 것을 아무도 못 본다.
여기서는 격자가 하나이고 배율만 다르다.

**왜 NEAREST 인가.** 이 게임은 픽셀 아트다(global.css 의 `image-rendering:
pixelated`). 32 를 6배·16배로 늘리는 것이라 두 크기 모두 정수 배율이고, 그래서
확대해도 원본 격자가 흐려지지 않는다 — 192/32 = 6, 512/32 = 16. 격자 크기를
바꾸려면 **192 와 512 를 동시에 나누는 수**여야 한다(8·16·32·64 뿐이다).
아래 _배율() 이 그것을 강제한다.

**왜 글자가 없는가.** 폰 홈 화면에서 이 그림은 48px 안팎으로 줄어든다. 그
크기에서 한글은 획이 뭉개져 이름표 노릇을 못 하고, 이름은 어차피 manifest 의
`short_name` 이 라벨로 따로 말한다.

**색은 tokens.css 에서 읽는다.** 여기 #hex 를 베껴 적으면 팔레트를 고치는 날
게임 화면만 바뀌고 홈 화면 아이콘은 옛 색으로 남는다 — 그리고 그 어긋남은
폰에서만 보인다. 아래 그림은 색 이름(토큰)으로만 그려져 있다.

Pillow 가 필요하다(이 기계에 10.4.0 이 있다). 없으면 `pip install pillow`.
"""

from __future__ import annotations

import math
import re
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # pragma: no cover - 사람이 읽을 안내가 스택트레이스보다 낫다
    sys.exit('Pillow 가 없다: pip install pillow')

저장소 = Path(__file__).resolve().parent.parent
토큰파일 = 저장소 / 'apps/client/src/styles/tokens.css'
결과폴더 = 저장소 / 'apps/client/public/app-icon'

# **`public/icons/` 가 아닌 이유**: 루트 .gitignore 가 그 폴더를 막는다(Pipoya
# 아이콘 76개가 거기 산다). 자체 제작한 이 그림을 거기 두면 커밋이 조용히
# 무시되고, 그러면 서버 PC 에는 영영 안 간다 — 배포는 사람이 dist 를 옮기는
# 절차이고 dist 는 커밋된 것에서 나오기 때문이다(scripts/ship-client.ps1).

크기들 = (192, 512)
격자 = 32

# 그림 — 구리 곡괭이 하나. 이 게임의 첫 도구가 구리 곡괭이·도끼·낫이고,
# 그중 곡괭이가 48px 에서 실루엣이 가장 또렷하다(도끼·낫은 날의 방향을 잃는다).
#
# **가운데로 모은 이유는 마스크형(maskable) 때문이다.** 안드로이드는 이 그림을
# 제 런처 모양(원·둥근 네모)으로 잘라 내므로, 안전 영역은 한가운데 지름 80%
# 원 하나다. 가장자리에는 배경색만 있고 곡괭이는 그 원 안에 들어간다 — 아래
# _안전영역검사() 가 매번 실제로 잰다. 그래서 manifest 가 이 파일 하나에
# `"purpose": "any maskable"` 둘을 함께 준다.
색표 = {
    '.': 'panel',           # 바탕 — 게임 패널의 나무색
    'H': 'accent',          # 날의 윗면 — 빛 받는 자리
    'C': 'tier-1',          # 곡괭이 머리. 등급 1 색이 곧 구리색이다
    'S': 'ink',             # 그림자. 바탕보다 어두워야 형태가 선다
    'L': 'parchment-dim',   # 자루의 왼쪽 하이라이트 — 없으면 48px 에서 자루가 바탕에 묻힌다
    'W': 'panel-edge',      # 자루의 나무
    'w': 'ink-soft',        # 자루의 오른쪽 그늘
}

그림 = (
    '................................',
    '................................',
    '................................',
    '................................',
    '................................',
    '................................',
    '................................',
    '...............HH...............',
    '...........HHHHCCHHHH...........',
    '........HHHCCCCCCCCCCHHH........',
    '......HHCCCCCCCCCCCCCCCCHH......',
    '.....HCCCCCSSCCCCCCSSCCCCCH.....',
    '.....CCCSSS..CCCCCC..SSSCCC.....',
    '.....CSS.....CCCCCC.....SSC.....',
    '.....S.......CCCCCC.......S.....',
    '.............SSSSSS.............',
    '.............LWWWw..............',
    '.............LWWWw..............',
    '.............LWWWw..............',
    '.............LWWWw..............',
    '.............LWWWw..............',
    '.............LWWWw..............',
    '.............LWWWw..............',
    '.............LWWWw..............',
    '.............LWWWw..............',
    '.............LWWWw..............',
    '.............SSSSS..............',
    '................................',
    '................................',
    '................................',
    '................................',
    '................................',
)


def _토큰읽기() -> dict[str, tuple[int, int, int]]:
    """tokens.css 의 `--c-*` 를 이름→RGB 로 돌려준다.

    파일을 읽는 것이지 값을 베끼는 것이 아니다 — 그것이 이 함수의 전부다.
    """
    본문 = 토큰파일.read_text(encoding='utf-8')
    표 = {}
    for 이름, hex값 in re.findall(r'--c-([\w-]+):\s*#([0-9a-fA-F]{6})\s*;', 본문):
        표[이름] = tuple(int(hex값[i:i + 2], 16) for i in (0, 2, 4))
    if not 표:
        raise SystemExit(f'{토큰파일} 에서 --c-* 를 하나도 못 읽었다 — 형식이 바뀌었는지 본다.')
    return 표


def _배율(크기: int) -> int:
    if 크기 % 격자 != 0:
        raise SystemExit(
            f'{크기} 는 격자 {격자} 로 안 나눠떨어진다 — 정수 배율이 아니면 '
            'NEAREST 확대가 픽셀을 고르지 않게 늘려 격자가 어긋난다.'
        )
    return 크기 // 격자


def _안전영역검사() -> None:
    """칠해진 픽셀이 마스크형 안전 영역(가운데 지름 80% 원) 안에 있는지 잰다.

    이 자를 스크립트 안에 두는 이유: 그림을 고치는 사람은 여기를 고치지
    테스트를 안 본다. 어긋나면 **굽는 자리에서** 서야 한다 — 안 그러면 안드로이드
    런처가 잘라 낸 뒤에야, 그것도 남의 폰에서야 알게 된다.
    """
    중심 = 격자 / 2
    반지름 = 격자 * 0.4
    벗어난것 = []
    for r, 줄 in enumerate(그림):
        for c, 문자 in enumerate(줄):
            if 문자 == '.':
                continue
            # 픽셀은 점이 아니라 1x1 네모다 — 네 모서리 중 가장 먼 것을 잰다.
            가장먼거리 = max(
                math.hypot(x - 중심, y - 중심)
                for x in (c, c + 1)
                for y in (r, r + 1)
            )
            if 가장먼거리 > 반지름:
                벗어난것.append(f'({r},{c})')
    if 벗어난것:
        raise SystemExit(
            '안전 영역 밖에 칠해진 픽셀이 있다 — 마스크형으로 잘린다: '
            + ', '.join(벗어난것)
        )


def main() -> None:
    _안전영역검사()
    토큰 = _토큰읽기()
    없는것 = sorted({이름 for 이름 in 색표.values() if 이름 not in 토큰})
    if 없는것:
        raise SystemExit(f'tokens.css 에 없는 토큰을 그림이 쓴다: {", ".join(없는것)}')

    if len(그림) != 격자 or any(len(줄) != 격자 for 줄 in 그림):
        raise SystemExit(f'그림이 {격자}x{격자} 가 아니다.')

    # **배율을 전부 먼저 잰다.** 굽는 도중에 서면 앞 크기는 새 그림, 뒤 크기는
    # 옛 그림으로 남아 manifest 가 적은 짝이 갈라진다 — 그 상태로도 빌드는
    # 멀쩡히 끝나고, webManifest.test.ts 는 크기만 재지 두 그림이 같은
    # 그림인지는 못 잰다. ship-client.ps1 이 관문을 robocopy **앞에** 두는 것과
    # 같은 자세다: 되돌리기 어려운 일 앞에 자를 세운다.
    배율표 = {크기: _배율(크기) for 크기 in 크기들}

    바탕 = Image.new('RGB', (격자, 격자))
    바탕.putdata([토큰[색표[문자]] for 줄 in 그림 for 문자 in 줄])

    결과폴더.mkdir(parents=True, exist_ok=True)
    for 크기, 배율 in 배율표.items():
        경로 = 결과폴더 / f'icon-{크기}.png'
        바탕.resize((크기, 크기), Image.NEAREST).save(경로)
        print(f'  {경로.relative_to(저장소)}  ({크기}x{크기}, 배율 x{배율})')


if __name__ == '__main__':
    main()
