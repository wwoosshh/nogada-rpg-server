/**
 * NPC 일과의 게임 규칙이 사는 곳.
 *
 * 지금은 상수 하나뿐이다. 위치를 실제로 계산하는 `npcStateAt` 은 다음 태스크에
 * 여기로 들어온다 — 먼저 이 파일을 여는 이유는 빌드(경로 굽기)와 런타임(위치
 * 보간)이 **같은 걸음 속도**를 봐야 하기 때문이다. 빌드가 400ms 로 역산한
 * 출발 시각을 런타임이 다른 속도로 걸으면, "닿는다"고 통과시킨 시간표에서
 * NPC 가 도착 시각에 아직 길 위에 있다.
 */

/**
 * NPC 가 한 칸을 걷는 데 걸리는 실측 시간.
 *
 * 플레이어(`STEP_MS = 200`)의 절반 속도다 — 주민이 플레이어와 같은 속도로
 * 돌아다니면 마을이 분주해 보이고, 무엇보다 "저 사람은 볼일이 있어 지나간다"가
 * 아니라 "나를 따라온다"로 읽힌다.
 *
 * 시간 축은 게임 분이 아니라 실측 ms 다. 게임 1분이 실측 2.5초라 분 단위로
 * 재면 NPC 가 2.5초에 여섯 칸씩 껑충 뛴다.
 */
export const NPC_STEP_MS = 400
