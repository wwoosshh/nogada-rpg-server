import type { ItemDef } from '../types.js'

/**
 * 상점이 파는 값 — 정가 그대로다(설계 §2).
 *
 * 함수 하나를 두는 이유는 계산이 어려워서가 아니라 **부르는 쪽이 여럿**이기
 * 때문이다: 서버의 매수 판정, 클라이언트의 총액 표시, 그리고 돈복사 금지 검증이
 * 같은 값을 봐야 한다. `def.price` 를 각자 읽으면 언젠가 한 곳만 할인을 붙인다.
 */
export function buyPrice(def: ItemDef): number {
  return def.price
}

/**
 * 상점이 사 주는 값 — 정가의 절반(내림)이다(설계 §2, 원작 규칙 그대로).
 *
 * **왜 절반인가:** 사고 바로 팔면 반드시 손해라, 상점을 왕복하는 무한 골드
 * 루프가 산술적으로 성립하지 않는다(설계 §6-앞 19 의 왕복 단조성).
 *
 * `price=0` 은 0 을 돌려준다. 이것은 "팔면 0원을 받는다"가 아니라 **팔 수
 * 없다**는 뜻이고(도구 13종이 그렇다), 거절 자체는 이 함수가 아니라 거래
 * 서비스의 규칙(`not_sellable`)이 한다 — 순수 계산 함수가 정책까지 들고 있으면
 * 화면이 값을 미리 보여줄 때도 그 정책을 통과해야 해서, 같은 규칙이 두 곳에
 * 생긴다.
 */
export function sellPrice(def: ItemDef): number {
  return Math.floor(def.price / 2)
}
